import anndata as ad
import pandas as pd

class CohortResult:
    """
    Encapsulates the outputs of the full cohort processing pipeline. This 
    object is immutable and represents all outputs generated by `prepare_project
    ()` excluding filesystem side effects.

    Attributes
    ----------
    cohort_adata : ad.AnnData
        Full processed cohort .h5ad AnnData object.
    train_adata : ad.AnnData | None
        Train split .h5ad AnnData object of the cohort.
    val_adata : ad.AnnData | None
        Validation split .h5ad AnnData object of the cohort.
    test_adata : ad.AnnData | None
        Test split .h5ad AnnData object of the cohort.
    probe_set : pd.Series
        Final probe set in order from the processed cohort.
    """

    def __init__(self,
                 cohort_adata: ad.AnnData,
                 train_adata: ad.AnnData | None,
                 val_adata: ad.AnnData | None,
                 test_adata: ad.AnnData | None,
                 probe_set: pd.Series):
        
        self.cohort_adata = cohort_adata
        self.train_adata = train_adata
        self.val_adata = val_adata
        self.test_adata = test_adata
        self.probe_set = probe_set

