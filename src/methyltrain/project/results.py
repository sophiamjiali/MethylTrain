import anndata as ad
import pandas as pd

from methyltrain.audit.audit_store import AuditStore

class ProjectResult:
    """
    Encapsulates the outputs of the full project processing pipeline. This 
    object is immutable and represents all outputs generated by `prepare_project
    ()` excluding filesystem side effects.

    Attributes
    ----------
    """

    def __init__(self,
                 adata: ad.AnnData,
                 manifest: pd.DataFrame,
                 metadata: pd.DataFrame,
                 download_report: list[dict],
                 metadata_report: list[dict],
                 biospecimen_report: list[dict],
                 cleaning_report: list[dict],
                 qc_report: list[dict]):
        
        self.adata = adata
        self.manifest = manifest
        self.metadata = metadata
        self.download_report = download_report
        self.metadata_report = metadata_report
        self.biospecimen_report = biospecimen_report
        self.cleaning_report = cleaning_report
        self.qc_report = qc_report